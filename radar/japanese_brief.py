_TERMS = {
    '原件证实':'一次資料で確認', '行业推演 · 待核实':'業界知見に基づく仮説・要確認',
    '業界推演 · 待核实':'業界知見に基づく仮説・要確認', '待核实':'要確認', '待核':'要確認',
    '临港':'臨港', '跨境空運':'国際航空輸送', '跨墶海运':'国際海上輸送',
    '跨境海運':'国際海上輸送', '城市配送':'都市内配送', '口岸':'港湾・空港',
    '拡産':'増産', '方案コンサルティング':'物流の設計支援',
    '入場ウィンドウ':'提案の好機', '入場の好機':'アプローチの好機',
    '設備入場':'設備搬入', '入場設備':'搬入設備', '入場部品':'工場納入部品',
    '入場配送':'工場への納入配送', '入場物流':'調達物流', '入場納品':'工場納入',
    'その場で結論を出さない':'その場で結論を求めない',
    '危険品':'危険物', '外包':'外部委託', '貨量':'取扱量', '流向':'貨物の流れ',
    '対応可能な実績':'対応可能なサービス', 'お伺いできればとおります':'お伺いできればと存じます',
    '中国区':'中国拠点', '二交代勤務':'2シフト勤務', '二交替勤務':'2シフト勤務',
}
_WIDE = str.maketrans({chr(i): chr(i - 0xFEE0) for a,b in ((0xFF10,0xFF19),(0xFF21,0xFF3A),(0xFF41,0xFF5A))
                      for i in range(a,b+1)})
_DANGER = re.compile(r'危険[品物](?:特[種殊])?物流')
_FORM = re.compile(r'記載済みの対応力|(?:業務|対応)範囲[^。！？\n]{0,20}(?:未記入|未確認(?:部分|項目))|未記入|入力欄|登録済みの対応(?:力|サービス|範囲)|記入済み(?:の対応|項目)|フォームの')
_SENTENCES = re.compile(r'(?<=[。！？；])|(?=\n)|(?<=\n)')


def normalize(text):
    text = _DANGER.sub('危険物物流',text.translate(_WIDE))
    for old,new in _TERMS.items():
        text = text.replace(old,new)
    text = re.sub(r'(?<!お)伺いできれば','お伺いできれば',text)
    # Internal commentary should disappear without losing facts in adjacent sentences.
    return ''.join(part for part in _SENTENCES.split(text) if not _FORM.search(part)).strip()


def language_issue(text):
    if _FORM.search(text):
        return '营业文案含表单状态'
    if re.search(r'入場|危険品|中国区|[０-９]|(?<!お)伺いできれば',text):
        return '日语术语、敬语或数字格式需要修改'
    return ''
